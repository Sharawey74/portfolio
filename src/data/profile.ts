import { z } from "zod";
import { claim } from "./schema.ts";

/**
 * Site-wide copy: hero, section indices, CTAs, footer microcopy.
 * Source "owner:approved-copy" means the line was approved by the owner, in the
 * build brief (2026-10-06) or in review round 1 (2026-10-08, docs/ISSUES.md
 * ISS-12), and is logged in FACTS-CHECK.md.
 */

const sectionSchema = z.object({
  id: z.string().regex(/^[a-z-]+$/),
  index: z.string().regex(/^\d{2}$/),
  title: z.string().min(1),
  /** Rendered on `/` yet? Nav links and CTAs point only at live sections. */
  live: z.boolean(),
});

const profileSchema = z.object({
  hero: z.object({
    /** Mono label above the H1. */
    label: claim,
    /** The public name. The final period is the one place body/heading text may use --break. */
    headline: claim,
    lead: claim,
    more: claim,
    ctaPrimary: z.object({ label: z.string(), href: z.string().startsWith("#") }),
    ctaResume: z.object({ label: z.string() }),
  }),
  sections: z.array(sectionSchema).min(1),
  meta: z.object({
    title: z.string().min(1),
    description: z.string().min(1).max(160),
    /** Mono footer line on share images; terms from the stack in About. */
    ogLine: z.string().min(1),
  }),
  /** Interface strings: controls and accessible names, not claims. */
  ui: z.object({
    skipToContent: z.string(),
    navLabel: z.string(),
    pauseAnimations: z.string(),
    playAnimations: z.string(),
    themeToLight: z.string(),
    themeToDark: z.string(),
    resumeUnavailable: z.string(),
    statusMerged: z.string(),
    statusOpen: z.string(),
    externalLink: z.string(),
    caseStudy: z.string(),
    alsoBuilt: z.string(),
    carouselLabel: z.string(),
    previous: z.string(),
    next: z.string(),
    slideOf: z.string(),
    zoom: z.string(),
    close: z.string(),
    source: z.string(),
    asOf: z.string(),
    back: z.string(),
    cursorView: z.string(),
    cursorZoom: z.string(),
    chartConfiguration: z.string(),
    chartNote: z.string(),
    caseSections: z.object({
      problem: z.string(),
      architecture: z.string(),
      decisions: z.string(),
      evidence: z.string(),
      stack: z.string(),
      caveats: z.string(),
      screenshots: z.string(),
    }),
    diagram: z.object({
      play: z.string(),
      pause: z.string(),
      step: z.string(),
      restart: z.string(),
      scrub: z.string(),
      scrollHint: z.string(),
      steps: z.string(),
    }),
    about: z.object({
      education: z.string(),
      internships: z.string(),
      openSource: z.string(),
      flagship: z.string(),
      mergedPrs: z.string(),
      acrossProjects: z.string(),
      location: z.string(),
      availability: z.string(),
      stack: z.string(),
      usedIn: z.string(),
      lanes: z.object({ backend: z.string(), data: z.string(), delivery: z.string(), ai: z.string(), frontend: z.string() }),
    }),
    oss: z.object({
      merged: z.string(),
      acrossProjects: z.string(),
      underReview: z.string(),
      opened: z.string(),
      mergedOn: z.string(),
      fixes: z.string(),
      lines: z.string(),
      issues: z.string(),
      closed: z.string(),
      liveStatus: z.string(),
      snapshotStatus: z.string(),
    }),
    experience: z.object({
      education: z.string(),
      certifications: z.string(),
      project: z.string(),
      gpa: z.string(),
    }),
    contact: z.object({
      lead: z.string(),
      direct: z.string(),
      email: z.string(),
      name: z.string(),
      message: z.string(),
      messageHint: z.string(),
      send: z.string(),
      sending: z.string(),
      sent: z.string(),
      invalid: z.string(),
      failed: z.string(),
      limited: z.string(),
      notConfigured: z.string(),
      honeypot: z.string(),
      required: z.string(),
    }),
    footer: z.object({
      nav: z.string(),
      /** Visible column titles (Stage 7 footer). */
      sectionsTitle: z.string(),
      elsewhereTitle: z.string(),
      backToTop: z.string(),
      sources: z.string(),
      license: z.string(),
      palette: z.string(),
    }),
    palette: z.object({
      open: z.string(),
      menu: z.string(),
      title: z.string(),
      placeholder: z.string(),
      empty: z.string(),
      hint: z.string(),
      groups: z.object({ sections: z.string(), projects: z.string(), openSource: z.string(), links: z.string(), actions: z.string() }),
      toggleTheme: z.string(),
      email: z.string(),
      resume: z.string(),
    }),
  }),
});

